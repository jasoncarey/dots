#!/usr/bin/env bash
# Claude Code status line: dir, git branch + state, node version, model, context usage.
input=$(cat);
cwd=$(echo "$input" | jq -r '.workspace.current_dir // .cwd');
cd "$cwd" 2>/dev/null || exit 0;
root=$(git --no-optional-locks rev-parse --show-toplevel 2>/dev/null);
if [ -n "$root" ];
then dir="$(basename "$root")${cwd#"$root"}";
else dir="${cwd/#$HOME/~}";
fi;
dir=$(echo "$dir" | awk -F/ '{n=NF;
if(n>3) print "…/"$(n-2)"/"$(n-1)"/"$n;
else print $0}');
printf '\033[1;36m%s\033[0m' "$dir";
if [ -n "$root" ];
then br=$(git --no-optional-locks symbolic-ref --short HEAD 2>/dev/null || git --no-optional-locks rev-parse --short HEAD 2>/dev/null);
printf ' on \033[1;35m%s\033[0m' "$br";
st=$(git --no-optional-locks status --porcelain=v1 -b 2>/dev/null);
f="";
echo "$st" | grep -qE '^(UU|AA|DD|AU|UA|DU|UD)' && f="$f=";
echo "$st" | grep -qE '^(.D|D.)' && f="$f✘";
echo "$st" | grep -qE '^R' && f="$f»";
echo "$st" | grep -qE '^.M' && f="$f!";
echo "$st" | grep -qE '^[MA]' && f="$f+";
echo "$st" | grep -q '^??' && f="$f?";
echo "$st" | head -1 | grep -q ahead && f="${f}⇡";
echo "$st" | head -1 | grep -q behind && f="${f}⇣";
[ -n "$f" ] && printf ' \033[1;31m[%s]\033[0m' "$f";
fi;
if [ -f package.json ] || [ -f .node-version ] || [ -f .nvmrc ];
then command -v node >/dev/null && printf ' via \033[1;32m%s\033[0m' "$(node --version)";
fi;
printf ' \033[2m%s\033[0m' "$(echo "$input" | jq -r '.model.display_name')";
pct=$(echo "$input" | jq -r '.context_window.used_percentage // empty');
if [ -n "$pct" ];
then p=$(printf '%.0f' "$pct");
if [ "$p" -gt 80 ];
then c=31;
elif [ "$p" -ge 50 ];
then c=33;
else c=32;
fi;
tin=$(echo "$input" | jq -r '.context_window.total_input_tokens // empty');
sz=$(echo "$input" | jq -r '.context_window.context_window_size // empty');
tk="";
[ -n "$tin" ] && [ -n "$sz" ] && tk=" $((tin/1000))k/$((sz/1000))k";
printf ' \033[1;%sm ctx %s%%%s\033[0m' "$c" "$p" "$tk";
fi;
printf '\n'
